"""Scenario eval: the operator's command for resolving waiting checkpoints.

Continues the recovery scenario one step further.  The real recovery command
files signed checkpoints for the held tasks; the operator command
(``execution/scripts/resolve_checkpoints.py``) then lists, shows, previews and
resolves them.  Signing uses a THROWAWAY key generated by the harness (never a
real one) whose thumbprint is pinned in every checkpoint's authority, and
submission goes through the real ``server._resolve_checkpoint`` and the real
Apis consumer.  Nothing between the signature and the dispatch boundary is
stubbed; only the terminal and the provider pace reading are simulated.

Each safety rule has a test that goes red when the rule is removed.
"""

