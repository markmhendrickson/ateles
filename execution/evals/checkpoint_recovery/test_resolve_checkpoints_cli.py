def test_signed_approval_releases_exactly_once_and_a_replay_does_nothing(
    ready, monkeypatch
):
    cp = ready.cp["ent_task_held_plain"]
    out = at_terminal(monkeypatch, "approve 1 checkpoints\n")
    code = cli(ready, "approve", "--checkpoint", cp, "--execute")
    text = out.getvalue()

    assert code == 0, text
    assert "1 of 1 confirmed by read-back" in text
    assert ready.dispatches.calls == [("ent_task_held_plain", "approved", True)]
    assert task_fields(ready, "ent_task_held_plain")["status"] == "routed"
    assert ready.entities[cp]["fields"]["status"] == "approved"
    assert ready.entities[cp]["fields"]["resolved_dispatched"] is True
    writes = len(ready.write_log)

    # The same approval again: no second write, no second dispatch.
    out = at_terminal(monkeypatch, "approve 1 checkpoints\n")
    code = cli(ready, "approve", "--checkpoint", cp, "--execute")

    assert len(ready.dispatches.calls) == 1
    assert len(ready.write_log) == writes
    assert "already resolved" in out.getvalue()


