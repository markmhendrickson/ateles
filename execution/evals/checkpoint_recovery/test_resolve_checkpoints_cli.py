TRIAGE = [
    {"task_entity_id": "ent_task_held_plain", "bucket": "SAFE",
     "reason": "analysis only", "task_title": "x"},
    {"task_entity_id": "ent_task_twin_a", "bucket": "SAFE", "reason": "twin a"},
    {"task_entity_id": "ent_task_twin_b", "bucket": "SAFE", "reason": "twin b"},
    {"task_entity_id": "ent_task_reject", "bucket": "STALE", "reason": "superseded"},
    {"task_entity_id": "ent_task_operator_only", "bucket": "OPERATOR",
     "reason": "needs a person"},
]


class Tty(io.StringIO):
    def isatty(self) -> bool:
        return True


@pytest.fixture(autouse=True)
def _no_agent_markers(monkeypatch):
    for name in rc.AGENT_ENV_MARKERS:
        monkeypatch.delenv(name, raising=False)


@pytest.fixture
def ready(world, monkeypatch, tmp_path, capsys):
    """Recovered checkpoints, a throwaway resolver key, a triage file, open pace."""
    code, lines = run(monkeypatch, capsys, "--apply")
    assert code == 0, lines
    key = tmp_path / "throwaway-resolver.jwk.json"
    key.write_text(json.dumps(dict(world.resolver.private_jwk)))
    monkeypatch.setenv("ATELES_CHECKPOINT_RESOLVER_JWK", str(key))
    triage = tmp_path / "triage.json"
    triage.write_text(json.dumps(TRIAGE))
    world.argv_base = ["--triage", str(triage)]
    world.private_d = world.resolver.private_jwk["d"]
    world.key_path = str(key)
    world.cp = {task: world.pending_checkpoints(task)[0] for task in HELD}
    set_pace(monkeypatch, allowed=True)
    # The reissue run's writes are the baseline for "nothing was written".
    world.baseline = list(world.write_log)
    return world


def set_pace(monkeypatch, *, allowed: bool) -> None:
    verdict = "ALLOWED" if allowed else "REFUSED"
    monkeypatch.setattr(
        harness_usage,
        "usage_report",
        lambda: {
            "p": {
                "usage_gate": {
                    "dispatch_allowed": allowed,
                    "summary": f"p: frontier dispatch {verdict} - test",
                }
            }
        },
    )


def cli(world, *argv) -> int:
    return rc.main([*world.argv_base, *argv])


def at_terminal(monkeypatch, typed: str) -> Tty:
    out = Tty()
    monkeypatch.setattr(sys, "stdin", Tty(typed))
    monkeypatch.setattr(sys, "stdout", out)
    return out


def task_fields(world, task_id):
    return world.entities[task_id]["fields"]


def written_since_baseline(world) -> list[str]:
    return world.write_log[len(world.baseline):]


# -- list / show -------------------------------------------------------------


def test_list_groups_by_bucket_and_says_what_each_action_does(ready, capsys):
    assert cli(ready, "list") == 0
    out = capsys.readouterr().out

    assert "== SAFE (3) ==" in out
    assert "== OPERATOR (1) ==" in out
    assert "== STALE (1) ==" in out
    # Tasks the triage file does not name are listed, not dropped.
    assert "== UNSORTED" in out
    assert ready.cp["ent_task_twin_a"] in out
    assert "DECLINES the task" in out
    assert "Held with no checkpoint" in out
    # The operator-only task says approving will not release it.
    operator_line = out.split("== OPERATOR (1) ==")[1].split("\n== ")[0]
    assert "will NOT release the task" in operator_line
    assert "releases the task to an agent" not in operator_line
    assert "ent_legacy_held" not in out, "a pre-signing brief is not resolvable"


